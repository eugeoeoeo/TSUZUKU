// ── Utility: Get today's word set ─────────────────────────────────────────────

/**
 * Returns the 20-word set for a given date.
 * Rotates through 7 sets based on day-of-week (0-6).
 */
export function getDailyWordSet(date: Date = new Date()): DailyWord[] {
  const dayOfWeek = date.getDay(); // 0 = Sunday ... 6 = Saturday
  return DAILY_WORD_SETS[dayOfWeek] ?? DAILY_WORD_SETS[0];
}

/**
 * Returns the current day index (0-6) to display "Day X of 7" messaging.
 */
export function getDailySetIndex(date: Date = new Date()): number {
  return date.getDay();
}
